/** Kill a single tmux session.  Returns `true` on success. */
export function killSession(name: string): boolean {
  try {
    execSync(`${baseCmd()} kill-session -t ${esc(name)}`, { stdio: "pipe" });
    return true;
  } catch {
    return false;
  }
}

